const dictionaries = { de, en } as const;
export type Locale = keyof typeof dictionaries;

function detectLocale(): Locale {
  // German is the product default; English is used only when the device explicitly prefers it.
  const code = getLocales()[0]?.languageCode ?? 'de';
  return code === 'en' ? 'en' : 'de';
}

type Ctx = { locale: Locale; t: (k: TKey, vars?: Record<string, string>) => string };
const I18nContext = createContext<Ctx>({ locale: 'de', t: (k) => de[k] });

export function I18nProvider({ children }: { children: React.ReactNode }) {
  const value = useMemo<Ctx>(() => {
    const locale = detectLocale();
    const dict = dictionaries[locale];
    return {
      locale,
      t: (k, vars) => {
        let s: string = dict[k] ?? de[k];
        if (vars) for (const [name, v] of Object.entries(vars)) s = s.replace(`{${name}}`, v);
        return s;
      },
    };
  }, []);
  return <I18nContext.Provider value={value}>{children}</I18nContext.Provider>;
}

export const useT = () => useContext(I18nContext).t;
